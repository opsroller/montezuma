"""Release notes and CHANGELOG.md from Conventional Commit subjects.

Releases are tags vX.Y.Z on main. A release's notes are the commits since
the previous release tag that is an ancestor of it, grouped by type.

Usage:
  changelog.py notes [--ref REF]
      Markdown notes for REF (default HEAD) since the previous release tag.
  changelog.py changelog [--next X.Y.Z] [--out FILE]
      The whole CHANGELOG.md: one section per release tag, newest first.
      --next adds a section for the untagged commits on HEAD under that
      version, for the release PR that comes before the tag.
  changelog.py check-tag TAG
      Exits non-zero unless TAG is vX.Y.Z.

Only the Python standard library and git are needed.
"""

import argparse
import re
import subprocess
import sys

TAG_RE = re.compile(r"^v(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$")
SUBJECT_RE = re.compile(r"^(?P<type>[a-z]+)(?:\((?P<scope>[^()]+)\))?(?P<bang>!)?: (?P<desc>.+)$")
BREAKING_RE = re.compile(r"^BREAKING[ -]CHANGE: ", re.MULTILINE)

SECTIONS = [
    ("breaking", "Breaking changes"),
    ("feat", "Features"),
    ("fix", "Fixes"),
    ("perf", "Performance"),
    ("other", "Other changes"),
]

HEADER = """<!-- SPDX-License-Identifier: GPL-2.0-or-later -->
# Changelog

Generated by `tools/release/changelog.py` from the Conventional Commit
titles on `main`; do not edit by hand. How releases are cut:
[Cut a release](docs/how-to/cut-a-release.md).
"""


def git(*args, check=True):
    result = subprocess.run(["git", *args], capture_output=True, text=True)
    if check and result.returncode != 0:
        sys.exit(f"git {' '.join(args)}: {result.stderr.strip()}")
    return result


def release_tags():
    """Release tags, oldest version first."""
    out = git("tag", "--list", "v[0-9]*").stdout.split()
    tags = [t for t in out if TAG_RE.match(t)]
    return sorted(tags, key=lambda t: tuple(int(n) for n in TAG_RE.match(t).groups()))


def is_ancestor(a, b):
    return git("merge-base", "--is-ancestor", a, b, check=False).returncode == 0


def previous_tag(ref, tags):
    """The newest release tag that is a strict ancestor of ref, or None."""
    sha = git("rev-parse", f"{ref}^{{commit}}").stdout.strip()
    for tag in reversed(tags):
        tag_sha = git("rev-parse", f"{tag}^{{commit}}").stdout.strip()
        if tag_sha != sha and is_ancestor(tag_sha, sha):
            return tag
    return None


def commits(since, ref):
    """(subject, body) of each non-merge commit in since..ref, oldest first."""
    span = f"{since}..{ref}" if since else ref
    out = git("log", "--no-merges", "--reverse", "--format=%s%x1f%b%x1e", span).stdout
    entries = []
    for record in out.split("\x1e"):
        record = record.strip("\n")
        if record:
            subject, _, body = record.partition("\x1f")
            entries.append((subject.strip(), body))
    return entries


def classify(subject, body, first=False):
    """(section key, line) for one commit, or None when it is left out.

    In the first release nothing came before, so nothing is breaking."""
    m = SUBJECT_RE.match(subject)
    if not m:
        return "other", subject
    kind, scope, desc = m["type"], m["scope"], m["desc"]
    # The release PR's own commit only regenerates this file.
    if kind == "chore" and scope == "release":
        return None
    line = f"**{scope}:** {desc}" if scope else desc
    if not first and (m["bang"] or BREAKING_RE.search(body)):
        return "breaking", line
    return (kind if kind in ("feat", "fix", "perf") else "other"), line


def render(entries, first=False):
    """Markdown sections for a list of (subject, body)."""
    grouped = {key: [] for key, _ in SECTIONS}
    for subject, body in entries:
        item = classify(subject, body, first)
        if item:
            grouped[item[0]].append(item[1])
    parts = []
    for key, title in SECTIONS:
        if grouped[key]:
            parts.append(f"### {title}\n\n" + "\n".join(f"- {line}" for line in grouped[key]) + "\n")
    return "\n".join(parts) if parts else "No changes.\n"


def tag_date(tag):
    return git("log", "-1", "--format=%cs", f"{tag}^{{commit}}").stdout.strip()


def notes(ref, tags):
    since = previous_tag(ref, tags)
    return render(commits(since, ref), first=since is None)


def changelog(tags, next_version=None):
    sections = []
    if next_version:
        head_tagged = any(
            git("rev-parse", f"{t}^{{commit}}").stdout == git("rev-parse", "HEAD^{commit}").stdout
            for t in tags
        )
        if not head_tagged:
            date = git("log", "-1", "--format=%cs", "HEAD").stdout.strip()
            sections.append(f"## v{next_version} ({date})\n\n" + notes("HEAD", tags))
    for tag in reversed(tags):
        sections.append(f"## {tag} ({tag_date(tag)})\n\n" + notes(tag, tags))
    return HEADER + "".join("\n" + s for s in sections)


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)
    p_notes = sub.add_parser("notes")
    p_notes.add_argument("--ref", default="HEAD")
    p_log = sub.add_parser("changelog")
    p_log.add_argument("--next", metavar="X.Y.Z")
    p_log.add_argument("--out")
    p_check = sub.add_parser("check-tag")
    p_check.add_argument("tag")
    args = parser.parse_args(argv)

    if args.command == "check-tag":
        if not TAG_RE.match(args.tag):
            sys.exit(f"{args.tag} is not a release tag (vX.Y.Z)")
        return
    if getattr(args, "next", None) and not TAG_RE.match(f"v{args.next}"):
        sys.exit(f"--next {args.next} is not X.Y.Z")

    tags = release_tags()
    if args.command == "notes":
        text = notes(args.ref, tags)
    else:
        text = changelog(tags, args.next)
    if getattr(args, "out", None):
        with open(args.out, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main(sys.argv[1:])
