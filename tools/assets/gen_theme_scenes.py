"""Write a board theme's Godot materials, scenes and manifest entry.

    python3 tools/assets/gen_theme_scenes.py [tools/assets/themes/temple.json]

Run after gen_theme_meshes.py and gen_theme_textures.py. Reads the theme
parameters and writes, as Godot text resources:

- game/assets/materials/<theme>/MI_*.tres   one per entry in "materials"
- game/assets/models/<theme>/**/PF_*.tscn    the scenes the manifest names
- game/assets/lookdev/LD_<Theme>.tscn        look-dev scene: whole board, game camera
- game/assets/manifest.json                  this theme's entry (others kept)
"""

import json
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HEADER = "; SPDX-License-Identifier: GPL-2.0-or-later\n; Generated by tools/assets/gen_theme_scenes.py; edit the theme parameters, not this file.\n"


def color(hex_str, alpha=1.0):
    h = hex_str.lstrip("#")
    r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
    return f"Color({r:.4f}, {g:.4f}, {b:.4f}, {alpha:.4f})"


class Resource:
    """Tiny writer for Godot's text resource format (.tres / .tscn)."""

    def __init__(self):
        self.ext = []  # (type, path)
        self.body = []

    def ext_id(self, rtype, path):
        key = (rtype, path)
        if key not in self.ext:
            self.ext.append(key)
        return f'ExtResource("{self.ext.index(key) + 1}")'

    def text(self, head):
        out = [head.format(steps=len(self.ext) + 1), HEADER]
        for i, (rtype, path) in enumerate(self.ext):
            out.append(f'[ext_resource type="{rtype}" path="{path}" id="{i + 1}"]')
        if self.ext:
            out.append("")
        out.extend(self.body)
        return "\n".join(out).rstrip() + "\n"


# The theme's "textures.sets", set by main(). Texture files are build outputs
# (gen_theme_textures.py), so paths follow the parameters, not the disk.
TEXTURE_SETS = {}


def texture_path(theme, tex_set, suffix, hi):
    """res:// path of one map of a texture set; the hi/ variant when asked for and the set has one."""
    name = f"T_{tex_set}_{suffix}.png"
    if hi and TEXTURE_SETS.get(tex_set, {}).get("hi"):
        return f"res://assets/textures/{theme}/hi/{name}"
    return f"res://assets/textures/{theme}/{name}"


def specular_from_ior(ior):
    """Godot's dielectric reflectance is 0.16 * specular^2; solve it for a real F0."""
    f0 = ((ior - 1) / (ior + 1)) ** 2
    return round(min(1.0, (f0 / 0.16) ** 0.5), 3)


def shader_material(spec, theme, hi):
    r = Resource()
    shader = r.ext_id("Shader", spec["shader"])
    # Procedural noise textures (heat haze), built by Godot at load time.
    for key, n in spec.get("noise_textures", {}).items():
        r.body += [f'[sub_resource type="FastNoiseLite" id="{key}_noise"]', f"seed = {n['seed']}",
                   f"frequency = {n['frequency']}", "",
                   f'[sub_resource type="NoiseTexture2D" id="{key}"]', f"width = {n['size']}", f"height = {n['size']}",
                   "seamless = true", f'noise = SubResource("{key}_noise")', ""]
    r.body += ["[resource]", f"shader = {shader}"]
    if "render_priority" in spec:
        r.body.append(f"render_priority = {spec['render_priority']}")
    for key in spec.get("noise_textures", {}):
        r.body.append(f'shader_parameter/{key} = SubResource("{key}")')
    # Build-output textures (fire flipbooks) by path under textures/<theme>/;
    # the desktop variant of a material takes the file's hi/ variant.
    for key, rel in spec.get("textures", {}).items():
        folder, _, name = rel.rpartition("/")
        rel = f"{folder}/hi/{name}" if hi else rel
        r.body.append(f"shader_parameter/{key} = {r.ext_id('Texture2D', f'res://assets/textures/{theme}/{rel}')}")
    if "set" in spec:
        for key, suffix in (("texture_albedo", "BC"), ("texture_normal", "N"), ("texture_orm", "ORM"), ("texture_height", "H")):
            if suffix != "H" or TEXTURE_SETS.get(spec["set"], {}).get("height"):
                path = texture_path(theme, spec["set"], suffix, hi)
                r.body.append(f"shader_parameter/{key} = {r.ext_id('Texture2D', path)}")
        r.body.append(f"shader_parameter/albedo = {color(spec.get('albedo_tint', spec['albedo']))}")
        r.body.append(f"shader_parameter/triplanar_scale = {spec.get('triplanar_scale', 1.0)}")
        r.body.append(f"shader_parameter/normal_scale = {spec.get('normal_scale', 1.0)}")
    if "ior" in spec and spec["shader"].endswith("SH_TriplanarPBR.gdshader"):
        r.body.append(f"shader_parameter/specular = {specular_from_ior(spec['ior'])}")
    for key, value in spec.get("params", {}).items():
        v = color(value) if isinstance(value, str) else value
        r.body.append(f"shader_parameter/{key} = {v}")
    return r.text('[gd_resource type="ShaderMaterial" load_steps={steps} format=3]')


def material(spec, theme, hi=False):
    """One Godot material from a theme material entry; hi=True writes the desktop variant."""
    if hi:
        spec = {k: v for k, v in spec.items() if k != "hi"} | spec.get("hi", {})
    if "shader" in spec:
        return shader_material(spec, theme, hi)

    r = Resource()
    orm = "set" in spec
    lines = ["[resource]", f"albedo_color = {color(spec.get('albedo_tint', spec['albedo']), spec.get('alpha', 1.0))}"]
    if orm:
        tex = {s: r.ext_id("Texture2D", texture_path(theme, spec["set"], s, hi)) for s in ("BC", "ORM", "N")}
        lines += [f"albedo_texture = {tex['BC']}", f"orm_texture = {tex['ORM']}"]
    specular = specular_from_ior(spec["ior"]) if "ior" in spec else spec.get("specular", 0.5)
    if orm:
        lines.append(f"metallic_specular = {specular}")
    else:
        lines += [f"metallic = {spec.get('metallic', 0.0)}", f"metallic_specular = {specular}",
                  f"roughness = {spec.get('roughness', 1.0)}"]
    if "emission" in spec:
        lines += ["emission_enabled = true", f"emission = {color(spec['emission'])}",
                  f"emission_energy_multiplier = {spec.get('emission_energy', 1.0)}"]
    if orm:
        lines += ["normal_enabled = true", f"normal_scale = {spec.get('normal_scale', 1.0)}",
                  f"normal_texture = {tex['N']}"]
    if "rim" in spec:
        lines += ["rim_enabled = true", f"rim = {spec['rim']}", f"rim_tint = {spec.get('rim_tint', 0.5)}"]
    if "clearcoat" in spec:
        lines += ["clearcoat_enabled = true", f"clearcoat = {spec['clearcoat']}",
                  f"clearcoat_roughness = {spec.get('clearcoat_roughness', 0.1)}"]
    if "anisotropy" in spec:
        lines += ["anisotropy_enabled = true", f"anisotropy = {spec['anisotropy']}"]
    if "subsurface" in spec:
        sss = spec["subsurface"]
        lines += ["subsurf_scatter_enabled = true", f"subsurf_scatter_strength = {sss['strength']}",
                  "subsurf_scatter_transmittance_enabled = true",
                  f"subsurf_scatter_transmittance_color = {color(sss['transmittance'])}",
                  f"subsurf_scatter_transmittance_depth = {sss.get('depth', 0.1)}",
                  f"subsurf_scatter_transmittance_boost = {sss.get('boost', 0.0)}"]
    if "backlight" in spec:
        lines += ["backlight_enabled = true", f"backlight = {color(spec['backlight'])}"]
    if spec.get("double_sided"):
        lines.append("cull_mode = 2")
    if "triplanar_scale" in spec:
        s = spec["triplanar_scale"]
        lines += ["uv1_scale = Vector3({0}, {0}, {0})".format(s), "uv1_triplanar = true",
                  "uv1_triplanar_sharpness = 4.0"]
        if spec.get("world_triplanar"):
            lines.append("uv1_world_triplanar = true")
    # The default trilinear repeat filter, not anisotropic: Godot's Metal
    # backend puts the anisotropic repeat sampler at slot 17, which GPUs
    # without argument buffers (16 sampler slots) cannot address. The desktop
    # shaders keep anisotropy through a clamped sampler (SH_Triplanar).
    r.body = lines
    kind = "ORMMaterial3D" if orm else "StandardMaterial3D"
    return r.text(f'[gd_resource type="{kind}" load_steps={{steps}} format=3]')


def mesh_scene(root_name, parts, theme):
    """A Node3D with one MeshInstance3D per (mesh, material) part."""
    r = Resource()
    r.body.append(f'[node name="{root_name}" type="Node3D"]')
    for name, mesh_path, mat in parts:
        mesh = r.ext_id("Mesh", mesh_path)
        mat_ref = r.ext_id("Material", f"res://assets/materials/{theme}/{mat}.tres")
        r.body += ["", f'[node name="{name}" type="MeshInstance3D" parent="."]', f"mesh = {mesh}",
                   f"surface_material_override/0 = {mat_ref}"]
    return r


def vec3(x, y, z):
    return f"Vector3({x}, {y}, {z})"


def fade_ramp(name, stops):
    """A Gradient and its texture for a particle colour ramp; stops are (offset, Color text)."""
    offsets = ", ".join(str(o) for o, _ in stops)
    colors = ", ".join(c.removeprefix("Color(").removesuffix(")") for _, c in stops)
    return [f'[sub_resource type="Gradient" id="{name}"]', f"offsets = PackedFloat32Array({offsets})",
            f"colors = PackedColorArray({colors})", "",
            f'[sub_resource type="GradientTexture1D" id="{name}_tex"]', f'gradient = SubResource("{name}")', ""]


def brazier_fire(p, theme):
    """PF_BrazierFire: flame, smoke and embers on GPU particles, heat haze and a flickering light.

    The origin sits at the centre of the bowl's rim. Tier switches are node
    groups read by QualityTiers (docs/reference/quality-tiers.md).
    """
    f, torch = p["fire"], p["environment"]["torch"]
    fl, sm, em, li, hz = f["flame"], f["smoke"], f["embers"], f["light"], f["haze"]
    r = Resource()
    mat = {n: r.ext_id("Material", f"res://assets/materials/{theme}/{n}.tres")
           for n in ("MI_Fire", "MI_FireSmoke", "MI_EmberTrail", "MI_Ember", "MI_HeatHaze")}
    white0, white1 = "Color(1, 1, 1, 0)", "Color(1, 1, 1, 1)"
    subs = []
    subs += fade_ramp("flame_fade", [(0.0, white0), (0.25, white1), (0.7, white1), (1.0, white0)])
    subs += fade_ramp("smoke_fade", [(0.0, white0), (0.3, "Color(1, 1, 1, 0.8)"), (1.0, white0)])
    subs += fade_ramp("ember_fade", [(0.0, "Color(1, 0.9, 0.6, 1)"), (0.35, "Color(1, 0.55, 0.15, 1)"),
                                      (0.8, "Color(0.7, 0.15, 0.03, 0.8)"), (1.0, "Color(0.4, 0.05, 0.0, 0)")])
    subs += ['[sub_resource type="Curve" id="smoke_grow"]',
             "_data = [Vector2(0, 0.45), 0.0, 0.0, 0, 0, Vector2(1, 1), 0.0, 0.0, 0, 0]", "point_count = 2", "",
             '[sub_resource type="CurveTexture" id="smoke_grow_tex"]', 'curve = SubResource("smoke_grow")', ""]
    subs += ['[sub_resource type="ParticleProcessMaterial" id="flame_process"]', "emission_shape = 1",
             f"emission_sphere_radius = {fl['emission_radius']}", f"emission_shape_offset = {vec3(0, fl['offset'], 0)}",
             f"direction = {vec3(0, 1, 0)}", "spread = 5.0",
             f"initial_velocity_min = {fl['velocity'][0]}", f"initial_velocity_max = {fl['velocity'][1]}",
             f"gravity = {vec3(0, 0, 0)}", f"angle_min = {-fl['angle']}", f"angle_max = {fl['angle']}",
             f"scale_min = {fl['scale'][0]}", f"scale_max = {fl['scale'][1]}",
             'color_ramp = SubResource("flame_fade_tex")', "",
             '[sub_resource type="QuadMesh" id="flame_quad"]', f"size = Vector2({fl['size'][0]}, {fl['size'][1]})",
             f"center_offset = {vec3(0, fl['size'][1] / 2, 0)}", ""]
    subs += ['[sub_resource type="ParticleProcessMaterial" id="smoke_process"]', "emission_shape = 1",
             f"emission_sphere_radius = {sm['emission_radius']}", f"emission_shape_offset = {vec3(0, sm['offset'], 0)}",
             f"direction = {vec3(0, 1, 0)}", "spread = 12.0",
             f"initial_velocity_min = {sm['velocity'][0]}", f"initial_velocity_max = {sm['velocity'][1]}",
             f"gravity = {vec3(0, 0.05, 0)}", "damping_min = 0.05", "damping_max = 0.1",
             "angle_min = -30.0", "angle_max = 30.0",
             f"scale_min = {sm['scale'][0]}", f"scale_max = {sm['scale'][1]}", 'scale_curve = SubResource("smoke_grow_tex")',
             'color_ramp = SubResource("smoke_fade_tex")', "turbulence_enabled = true",
             f"turbulence_noise_strength = {sm['turbulence']}", "turbulence_noise_scale = 4.0",
             "turbulence_influence_min = 0.02", "turbulence_influence_max = 0.06", "",
             '[sub_resource type="QuadMesh" id="smoke_quad"]', f"size = Vector2({sm['size'][0]}, {sm['size'][1]})", ""]
    subs += ['[sub_resource type="ParticleProcessMaterial" id="ember_process"]', "emission_shape = 1",
             f"emission_sphere_radius = {em['emission_radius']}", f"emission_shape_offset = {vec3(0, 0.1, 0)}",
             f"direction = {vec3(0, 1, 0)}", f"spread = {em['spread']}",
             f"initial_velocity_min = {em['velocity'][0]}", f"initial_velocity_max = {em['velocity'][1]}",
             f"gravity = {vec3(0, -0.25, 0)}", "damping_min = 0.3", "damping_max = 0.6",
             "scale_min = 0.6", "scale_max = 1.2", 'color_ramp = SubResource("ember_fade_tex")',
             "turbulence_enabled = true", f"turbulence_noise_strength = {em['turbulence']}",
             "turbulence_noise_scale = 2.5", "turbulence_noise_speed = Vector3(0, 0.6, 0)",
             "turbulence_influence_min = 0.05", "turbulence_influence_max = 0.15", "",
             '[sub_resource type="TubeTrailMesh" id="ember_tube"]', f"radius = {em['size'] / 2}",
             "radial_steps = 4", "sections = 4", "section_length = 0.05", "section_rings = 1", "cap_top = false",
             "cap_bottom = false", "",
             '[sub_resource type="QuadMesh" id="ember_quad"]', f"size = Vector2({em['size'] * 2}, {em['size'] * 2})", "",
             '[sub_resource type="QuadMesh" id="haze_quad"]', f"size = Vector2({hz['size'][0]}, {hz['size'][1]})",
             f"center_offset = {vec3(0, hz['size'][1] / 2, 0)}", ""]
    aabb = "AABB(-1.5, -0.5, -1.5, 3, 4, 3)"

    def particles(name, amount, lifetime, process, mesh, material, extra=(), groups=None):
        head = f'[node name="{name}" type="GPUParticles3D" parent="."'
        head += f' groups=["{groups}"]]' if groups else "]"
        return ["", head, "cast_shadow = 0", f"amount = {amount}", f"lifetime = {lifetime}", f"preprocess = {lifetime}",
                f"visibility_aabb = {aabb}", f'process_material = SubResource("{process}")',
                f'draw_pass_1 = SubResource("{mesh}")', f"material_override = {material}", *extra]

    r.body = subs + ['[node name="BrazierFire" type="Node3D"]']
    r.body += particles("Smoke", sm["amount"], sm["lifetime"], "smoke_process", "smoke_quad", mat["MI_FireSmoke"],
                        ["draw_order = 1"])
    r.body += particles("Flame", fl["amount"], fl["lifetime"], "flame_process", "flame_quad", mat["MI_Fire"])
    # The trail mesh waits in metadata: QualityTiers attaches it and turns
    # trails on only where the tier has them (Compatibility warns otherwise).
    r.body += particles("Embers", em["amount"], em["lifetime"], "ember_process", "ember_quad", mat["MI_EmberTrail"],
                        [f"trail_lifetime = {em['trail_lifetime']}", 'metadata/trail_mesh = SubResource("ember_tube")'],
                        groups="quality:particle_trails")
    r.body += particles("EmbersNoTrail", em["amount"], em["lifetime"], "ember_process", "ember_quad", mat["MI_Ember"],
                        groups="quality_fallback:particle_trails")
    r.body += ["", '[node name="HeatHaze" type="MeshInstance3D" parent="." groups=["quality:heat_haze"]]',
               f"transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, 0, {hz['offset']}, 0)", "cast_shadow = 0",
               'mesh = SubResource("haze_quad")', f"surface_material_override/0 = {mat['MI_HeatHaze']}"]
    r.body += ["", '[node name="Light" type="FlickerLight3D" parent="." groups=["quality_shadow_light", "quality_fog_light"]]',
               f"transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, 0, {li['height']}, 0)",
               f"light_color = {color(torch['color'])}", f"light_energy = {torch['energy']}",
               f"light_volumetric_fog_energy = {li['fog_energy']}", "light_bake_mode = 2", "shadow_enabled = true",
               f"shadow_blur = {li['shadow_blur']}", f"omni_range = {torch['range']}", "omni_attenuation = 1.4",
               f"flicker = {li['flicker']}", f"speed = {li['speed']}", f"sway = {li['sway']}"]
    return r.text("[gd_scene load_steps={steps} format=3]")


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def main():
    params_path = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "tools/assets/themes/temple.json"
    p = json.loads(params_path.read_text())
    theme = p["theme"]
    TEXTURE_SETS.update(p["textures"]["sets"])
    assets = ROOT / "game/assets"
    models = f"res://assets/models/{theme}"
    entry = {}

    for name, spec in p["materials"].items():
        write(assets / "materials" / theme / f"{name}.tres", material(spec, theme))
        if "hi" in spec:
            write(assets / "materials" / theme / "hi" / f"{name}.tres", material(spec, theme, hi=True))

    for kind in p["artifacts"]["kinds"]:
        r = mesh_scene(kind["name"], [("Mesh", f"{models}/artifacts/SM_Artifact_{kind['name']}.obj", kind["material"])],
                       theme)
        rel = f"models/{theme}/artifacts/PF_Artifact_{kind['name']}.tscn"
        write(assets / rel, r.text("[gd_scene load_steps={steps} format=3]"))
        entry[f"artifact_{kind['index']}"] = f"res://assets/{rel}"

    board_parts = [("TilesLight", "MI_StoneTileLight"), ("TilesDark", "MI_StoneTileDark"), ("Base", "MI_StoneDark"),
                   ("Frame", "MI_StoneFrame"), ("Fret", "MI_StoneFrame"), ("Gold", "MI_Gold")]
    r = mesh_scene("Board", [(n, f"{models}/board/SM_Board_{n}.obj", m) for n, m in board_parts], theme)
    write(assets / f"models/{theme}/board/PF_Board.tscn", r.text("[gd_scene load_steps={steps} format=3]"))
    entry["board"] = f"{models}/board/PF_Board.tscn"

    backdrop_parts = [("Stone", "MI_StoneFrame"), ("StoneDark", "MI_StoneDark"), ("Bronze", "MI_Bronze"),
                      ("Ground", "MI_Ground"), ("Foliage", "MI_Foliage"), ("Rocks", "MI_StoneDark")]
    r = mesh_scene("Environment", [(n, f"{models}/backdrop/SM_Backdrop_{n}.obj", m) for n, m in backdrop_parts], theme)
    env = p["environment"]
    sky = [
        "[sub_resource type=\"ProceduralSkyMaterial\" id=\"sky_mat\"]",
        f"sky_top_color = {color(env['sky_top'])}",
        f"sky_horizon_color = {color(env['sky_horizon'])}",
        f"ground_bottom_color = {color(env['ground_bottom'])}",
        f"ground_horizon_color = {color(env['sky_horizon'])}",
        "sun_angle_max = 20.0",
        "",
        "[sub_resource type=\"Sky\" id=\"sky\"]",
        "sky_material = SubResource(\"sky_mat\")",
        "",
        "[sub_resource type=\"Environment\" id=\"env\"]",
        "background_mode = 2",
        "sky = SubResource(\"sky\")",
        "ambient_light_source = 3",
        f"ambient_light_energy = {env['ambient_energy']}",
        "reflected_light_source = 2",
        "tonemap_mode = 2",
        f"tonemap_exposure = {env['exposure']}",
        "glow_enabled = true",
        "glow_intensity = 0.6",
        "glow_bloom = 0.05",
        "glow_hdr_threshold = 1.1",
        "fog_enabled = true",
        f"fog_light_color = {color(env['fog'])}",
        f"fog_density = {env['fog_density']}",
        "fog_sky_affect = 0.3",
        "adjustment_enabled = true",
        f"adjustment_saturation = {env['saturation']}",
        "",
    ]
    r.body = sky + r.body
    sun = env["sun"]
    r.body += ["", '[node name="WorldEnvironment" type="WorldEnvironment" parent="."]', 'environment = SubResource("env")',
               "", '[node name="Sun" type="DirectionalLight3D" parent="."]', f"transform = {sun['transform']}",
               f"light_color = {color(sun['color'])}", f"light_energy = {sun['energy']}", "shadow_enabled = true",
               "directional_shadow_max_distance = 40.0"]
    # A fire in each brazier (the braziers stand on pillars at the corners,
    # gen_theme_meshes.py); each carries its own flickering light.
    half = p["board"]["width"] * p["cell_size"] / 2 + p["board"]["frame_width"] + 0.95
    fire_scene = f"{models}/fx/fire/PF_BrazierFire.tscn"
    write(assets / f"models/{theme}/fx/fire/PF_BrazierFire.tscn", brazier_fire(p, theme))
    for i, (sx, sz) in enumerate(((-1, -1), (1, -1), (-1, 1), (1, 1))):
        r.body += ["", f'[node name="Fire{i + 1}" parent="." instance={r.ext_id("PackedScene", fire_scene)}]',
                   f"transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, {sx * half}, {p['fire']['rim_height']}, {sz * half})"]
    write(assets / f"models/{theme}/backdrop/PF_Environment.tscn", r.text("[gd_scene load_steps={steps} format=3]"))
    entry["environment"] = f"{models}/backdrop/PF_Environment.tscn"

    # Selected-cell glow, a 1x1 plane just above the tile tops.
    r = Resource()
    mat = r.ext_id("Material", f"res://assets/materials/{theme}/MI_CellHighlight.tres")
    r.body = ['[sub_resource type="PlaneMesh" id="plane"]', "size = Vector2(1, 1)", "",
              '[node name="CellHighlight" type="MeshInstance3D"]',
              "transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, 0, 0.01, 0)", 'mesh = SubResource("plane")',
              f"surface_material_override/0 = {mat}", "cast_shadow = 0"]
    write(assets / f"models/{theme}/fx/PF_CellHighlight.tscn", r.text("[gd_scene load_steps={steps} format=3]"))
    entry["cell_highlight"] = f"{models}/fx/PF_CellHighlight.tscn"

    # Match burst: one-shot sparks; the view frees it after `lifetime`.
    r = Resource()
    mat = r.ext_id("Material", f"res://assets/materials/{theme}/MI_Spark.tres")
    r.body = ['[sub_resource type="SphereMesh" id="spark"]', "radius = 0.035", "height = 0.07",
              "radial_segments = 6", "rings = 3", "",
              '[node name="MatchBurst" type="CPUParticles3D"]', "emitting = true", "amount = 16",
              "lifetime = 0.55", "one_shot = true", "explosiveness = 0.95", 'mesh = SubResource("spark")',
              f"material_override = {mat}", "emission_shape = 1", "emission_sphere_radius = 0.25",
              "direction = Vector3(0, 1, 0)", "spread = 70.0", "gravity = Vector3(0, -7, 0)",
              "initial_velocity_min = 1.6", "initial_velocity_max = 3.0", "scale_amount_min = 0.6",
              "scale_amount_max = 1.3"]
    write(assets / f"models/{theme}/fx/PF_MatchBurst.tscn", r.text("[gd_scene load_steps={steps} format=3]"))
    entry["fx_match"] = f"{models}/fx/PF_MatchBurst.tscn"

    # Look-dev scenes, once per tier: base materials (mobile, web) and, as *_Hi,
    # the desktop variants from materials/<theme>/hi/ swapped in on every part
    # that has one, the way the quality tier system resolves them in game.
    kind_material = {k["index"]: k["material"] for k in p["artifacts"]["kinds"]}
    tiered = [("Board", n, m) for n, m in board_parts] + [("Environment", n, m) for n, m in backdrop_parts]

    def hi_overrides(r, parts):
        for parent, child, mat in parts:
            if "hi" in p["materials"][mat]:
                ref = r.ext_id("Material", f"res://assets/materials/{theme}/hi/{mat}.tres")
                r.body += ["", f'[node name="{child}" parent="{parent}"]', f"surface_material_override/0 = {ref}"]

    for suffix in ("", "_Hi"):
        # Look-dev: the whole theme from the game camera, on a seeded random board.
        r = Resource()
        r.body = [f'[node name="LookDev_{theme}" type="Node3D"]', "",
                  f'[node name="Environment" parent="." instance={r.ext_id("PackedScene", entry["environment"])}]', "",
                  f'[node name="Board" parent="." instance={r.ext_id("PackedScene", entry["board"])}]', "",
                  '[node name="Camera" type="Camera3D" parent="."]',
                  f"transform = {p['lookdev']['camera_transform']}", f"fov = {p['lookdev']['fov']}"]
        rng = random.Random(p["seed"])
        w, h = p["board"]["width"], p["board"]["height"]
        kinds = len(p["artifacts"]["kinds"])
        pieces = []
        for y in range(h):
            for x in range(w):
                k = rng.randrange(kinds)
                px, pz = (x - (w - 1) / 2) * p["cell_size"], (y - (h - 1) / 2) * p["cell_size"]
                r.body += ["", f'[node name="P{x}_{y}" parent="." instance={r.ext_id("PackedScene", entry[f"artifact_{k}"])}]',
                           f"transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, {px}, 0, {pz})"]
                pieces.append((f"P{x}_{y}", "Mesh", kind_material[k]))
        hx, hy = p["lookdev"]["highlight_cell"]
        r.body += ["", f'[node name="Highlight" parent="." instance={r.ext_id("PackedScene", entry["cell_highlight"])}]',
                   f"transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, {(hx - (w - 1) / 2)}, 0.01, {(hy - (h - 1) / 2)})"]
        if suffix:
            hi_overrides(r, tiered + pieces)
        write(assets / f"lookdev/LD_{theme.capitalize()}{suffix}.tscn", r.text("[gd_scene load_steps={steps} format=3]"))

        # Look-dev line-up: the seven pieces side by side, close up, for silhouette and value checks.
        r = Resource()
        r.body = [f'[node name="LineUp_{theme}" type="Node3D"]', "",
                  f'[node name="Environment" parent="." instance={r.ext_id("PackedScene", entry["environment"])}]', "",
                  f'[node name="Board" parent="." instance={r.ext_id("PackedScene", entry["board"])}]', "",
                  '[node name="Camera" type="Camera3D" parent="."]',
                  "transform = Transform3D(1, 0, 0, 0, 0.5, 0.866025, 0, -0.866025, 0.5, 0, 4.6, 3.1)", "fov = 40.0"]
        for k in range(kinds):
            r.body += ["", f'[node name="K{k}" parent="." instance={r.ext_id("PackedScene", entry[f"artifact_{k}"])}]',
                       f"transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, {k - (kinds - 1) / 2}, 0, 0.5)"]
        if suffix:
            hi_overrides(r, tiered + [(f"K{k}", "Mesh", kind_material[k]) for k in range(kinds)])
        write(assets / f"lookdev/LD_{theme.capitalize()}_LineUp{suffix}.tscn",
              r.text("[gd_scene load_steps={steps} format=3]"))

    # Look-dev close-up of one brazier fire (three-quarter view from outside the
    # platform, board behind), base and desktop (hi/ fire materials).
    for suffix in ("", "_Hi"):
        r = Resource()
        r.body = [f'[node name="LookDevFire_{theme}" type="Node3D"]', "",
                  f'[node name="Environment" parent="." instance={r.ext_id("PackedScene", entry["environment"])}]', "",
                  f'[node name="Board" parent="." instance={r.ext_id("PackedScene", entry["board"])}]', "",
                  '[node name="Camera" type="Camera3D" parent="."]',
                  f"transform = {p['lookdev']['fire_camera_transform']}", f"fov = {p['lookdev']['fire_fov']}"]
        if suffix:
            hi_overrides(r, tiered)
            for i in range(4):
                for node, mat in (("Flame", "MI_Fire"), ("Smoke", "MI_FireSmoke")):
                    ref = r.ext_id("Material", f"res://assets/materials/{theme}/hi/{mat}.tres")
                    r.body += ["", f'[node name="{node}" parent="Environment/Fire{i + 1}"]', f"material_override = {ref}"]
        write(assets / f"lookdev/LD_{theme.capitalize()}_Fire{suffix}.tscn", r.text("[gd_scene load_steps={steps} format=3]"))

    # Piece and board colours for 2D use (HUD quota swatches), derived from the same parameters.
    names = ["red", "orange", "yellow", "green", "blue", "purple", "white"]
    m = p["materials"]
    tokens = {
        "$description": f"{theme} board theme colours (sRGB hex) for use outside the 3D board, such as HUD quota icons. "
                        "Generated by tools/assets/gen_theme_scenes.py from tools/assets/themes/"
                        f"{theme}.json; edit that file, not this one. SPDX-License-Identifier: GPL-2.0-or-later",
        "kind": {str(k["index"]): {"name": names[k["index"]], "artifact": k["name"], "value": m[k["material"]]["albedo"]}
                 for k in p["artifacts"]["kinds"]},
        "surface": {key: m[mat]["albedo"] for key, mat in p.get("surface_tokens", {}).items()}
                   | {key: value for key, value in p.get("extra_tokens", {}).items()},
    }
    write(ROOT / "design/tokens" / f"{theme}-board.json", json.dumps(tokens, indent=2) + "\n")

    manifest_path = assets / "manifest.json"
    manifest = json.loads(manifest_path.read_text()) if manifest_path.exists() else {}
    manifest.setdefault("default_theme", theme)
    manifest.setdefault("themes", {})[theme] = entry
    manifest["themes"] = dict(sorted(manifest["themes"].items()))
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"{theme}: {len(p['materials'])} materials, {len(entry)} manifest names")


if __name__ == "__main__":
    main()
